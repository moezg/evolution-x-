def _patch_prospective(monkeypatch, root, bars: Bars) -> None:
    monkeypatch.setattr(P, "OUT", root)
    monkeypatch.setattr(P, "FRESH", root)
    monkeypatch.setattr(P, "SNAPSHOTS", root / "snapshots")
    monkeypatch.setattr(P, "load_bars", lambda: bars)


def test_interrupted_issuance_resumes_without_duplicates_or_changes(ops, monkeypatch):
    b = synth_bars(460, seed=5)
    _patch_prospective(monkeypatch, ops.root.parent, b)
    led = ForecastLedger()
    now = dt.datetime.fromtimestamp((int(b.open_time[-1]) + 3 * HOUR) / 1000, dt.UTC)
    real_issue, n = ForecastLedger.issue, {"k": 0}

    def crash_after_10(self, rec, now_ms=None):
        n["k"] += 1
        if n["k"] > 10:
            raise KeyboardInterrupt("synthetic kill -9 during issuance")
        return real_issue(self, rec, now_ms)

    monkeypatch.setattr(ForecastLedger, "issue", crash_after_10)
    with pytest.raises(KeyboardInterrupt):
        P.issue(now=now, fetch=False, ledger=led)
    before = led.j.path.read_text()
    assert len(led.forecasts()) == 10
    monkeypatch.setattr(ForecastLedger, "issue", real_issue)
    r = P.issue(now=now + dt.timedelta(minutes=5), fetch=False, ledger=led)
    assert sum(1 for f in r["forecasts"] if "skipped" in f) == 10
    assert len(led.forecasts()) == 32 and len(led.entries()) == 32
    assert led.j.path.read_text().startswith(before)  # the first 10 records are byte-identical
    assert led.verify()["ok"]
    r2 = P.issue(now=now + dt.timedelta(minutes=10), fetch=False, ledger=led)
    assert all("skipped" in f for f in r2["forecasts"]) and len(led.entries()) == 32
    monkeypatch.setattr(P, "code_version", lambda: "a-later-commit")  # version change between runs (e.g. a commit)
    r3 = P.issue(now=now + dt.timedelta(minutes=15), fetch=False, ledger=led)
    assert all("skipped" in f for f in r3["forecasts"]) and len(led.entries()) == 32  # no second set
    snap = led.entries()[0]["data"]["input_snapshot"]
    assert snap["sha256"] and snap["bars"] > 0
    assert led.entries()[0]["data"]["feature_version"] == P.FEATURE_VERSION


