def _counter_job(name: str, critical: bool = True, fail_times: int = 0, slot: str = "s1", calls: list | None = None):
    calls = calls if calls is not None else []

    def run(s, now, db):
        calls.append((name, s))
        if len([c for c in calls if c[0] == name]) <= fail_times:
            raise RuntimeError(f"synthetic failure of {name}")
        return {"ok": True}

    return S.Job(name, critical, lambda now: slot, run, max_attempts=3), calls


# --------------------------------------------------------------------------- scheduler core
def test_slot_runs_exactly_once_across_repeated_ticks(ops):
    job, calls = _counter_job("a")
    for _ in range(4):
        S.tick([job], NOW, ops)
    assert calls == [("a", "s1")]
    assert ops.q("SELECT status, attempts FROM runs")[0] == {"status": "succeeded", "attempts": 1}
    assert ops.q("SELECT value FROM heartbeat WHERE key='last_tick_utc'")


def test_overlapping_tick_is_refused_by_the_lock(ops):
    job, calls = _counter_job("a")
    with S.tick_lock(ops.root) as ok:
        assert ok
        r = S.tick([job], NOW, ops)
    assert r["status"] == "locked" and calls == []
    assert S.tick([job], NOW, ops)["status"] == "ran" and calls == [("a", "s1")]


def test_run_left_running_by_a_killed_process_is_recovered_after_its_lease(ops):
    job, calls = _counter_job("a")
    ops.x(
        "INSERT INTO runs (job, slot, critical, status, attempts, lease_until) VALUES ('a','s1',1,'running',1,?)",
        (time.time() + 600,),
    )
    S.tick([job], NOW, ops)
    assert calls == []  # a live lease belongs to another process
    ops.x("UPDATE runs SET lease_until=? WHERE job='a'", (time.time() - 1,))
    S.tick([job], NOW, ops)
    assert calls == [("a", "s1")]
    assert ops.q("SELECT status, attempts FROM runs")[0] == {"status": "succeeded", "attempts": 2}


def test_exponential_backoff_then_failure_notification(ops):
    job, calls = _counter_job("a", fail_times=10)
    cfg = {"backoff_s": 100.0}
    S.tick([job], NOW, ops, cfg)
    r = ops.q("SELECT status, attempts, next_attempt_utc FROM runs")[0]
    assert r["status"] == "retry" and r["attempts"] == 1
    first_wait = dt.datetime.fromisoformat(r["next_attempt_utc"]) - dt.datetime.now(dt.UTC)
    assert 90 < first_wait.total_seconds() <= 100
    S.tick([job], NOW, ops, cfg)
    assert len(calls) == 1  # still backing off
    for k in (2, 3):
        ops.x("UPDATE runs SET next_attempt_utc=NULL")
        S.tick([job], NOW, ops, cfg)
        if k == 2:
            nxt = dt.datetime.fromisoformat(ops.q("SELECT next_attempt_utc FROM runs")[0]["next_attempt_utc"])
            assert 190 < (nxt - dt.datetime.now(dt.UTC)).total_seconds() <= 200  # doubled
    assert ops.q("SELECT status, attempts FROM runs")[0] == {"status": "failed", "attempts": 3}
    levels = [n["level"] for n in ops.q("SELECT level FROM notifications ORDER BY id")]
    assert levels == ["warning", "warning", "error"]
    S.tick([job], NOW, ops, cfg)
    assert len(calls) == 3  # a failed slot is terminal


def test_pending_wait_does_not_consume_attempts(ops):
    n = {"k": 0}

    def run(s, now, db):
        n["k"] += 1
        return {"_status": "pending", "_retry_after_s": 0} if n["k"] < 5 else {"done": True}

    job = S.Job("w", True, lambda now: "s", run, max_attempts=2)
    for _ in range(5):
        S.tick([job], NOW, ops)
    assert ops.q("SELECT status, attempts FROM runs")[0] == {"status": "succeeded", "attempts": 1}


