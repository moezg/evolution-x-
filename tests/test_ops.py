# --------------------------------------------------------------------------- ledger: missed windows, no backfill
def test_missed_origins_are_recorded_once_and_never_backfilled(ops, monkeypatch):
    start = dt.datetime(2026, 11, 4, tzinfo=dt.UTC)
    monkeypatch.setattr(J, "SCHEDULE_START", start)
    now = start + dt.timedelta(days=2, hours=1)
    r = J.forecast_missed_check("x", now, ops)
    assert len(r["recorded_missed"]) == 3  # 11-04, 11-05, 11-06 00:00 all passed without a forecast
    assert J.forecast_missed_check("y", now, ops)["recorded_missed"] == []
    led = ForecastLedger()
    o = int(start.timestamp() * 1000)
    rec = {"id": "late", "domain": "btc_perp", "target": "rv_24", "model": "M1", "model_version": "v",
           "origin_ms": o, "window_end_ms": o + 24 * HOUR, "as_of_ms": o - 48 * HOUR, "inputs": {}}  # fmt: skip
    with pytest.raises(LedgerError):  # even with a forged early clock, a missed origin can never get a forecast
        led.issue(rec, now_ms=o - HOUR)
    with pytest.raises(LedgerError):
        led.record_missed("btc_perp", o + 10 * 86_400_000, "future", now_ms=o)  # cannot pre-declare a miss
    v = led.verify()
    assert v["ok"] and v["missed"] == 3
    o2 = o + 10 * 86_400_000
    led.issue({**rec, "id": "a", "origin_ms": o2, "window_end_ms": o2 + 24 * HOUR}, now_ms=o2 - HOUR)
    with pytest.raises(LedgerError, match="already exists"):  # same origin/target/model under another version
        led.issue(
            {**rec, "id": "b", "model_version": "v2", "origin_ms": o2, "window_end_ms": o2 + 24 * HOUR},
            now_ms=o2 - HOUR,
        )


